package io.github.wolfandrei.repodocs.site

import java.io.File
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertFalse
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.BeforeEach
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir

/** Dokka pages in the shape Dokka 2 writes them, reduced to what the site takes. */
internal class DokkaReferenceTest {
    @TempDir
    lateinit var dir: File

    private fun page(path: String, main: String) {
        dir.resolve(path).apply { parentFile.mkdirs() }.writeText(
            """
            |<!doctype html><html><head><script src="../scripts/main.js"></script></head><body>
            |<div class="root"><header class="navigation" id="navigation-wrapper">Dokka header</header>
            |<div id="container"><nav id="leftColumn" class="sidebar">Dokka sidebar</nav>
            |<div id="main">$main
            |<div class="footer">Generated by Dokka</div></div></div></div></body></html>
            """.trimMargin()
        )
    }

    @BeforeEach
    fun writeReference() {
        page(
            "lib/com.example/-greeter/index.html",
            """
            |<div class="main-content" data-page-type="classlike" id="content">
            |<div class="breadcrumbs"><a href="../../index.html">lib</a><span class="delimiter">/</span>
            |<a href="../index.html">com.example</a><span class="delimiter">/</span>
            |<span class="current">Greeter</span></div>
            |<div class="cover "><h1 class="cover"><span><span>Greeter</span></span></h1>
            |<div class="platform-hinted " data-platform-hinted="data-platform-hinted">
            |<div class="content sourceset-dependent-content" data-active="" data-togglable=":lib/commonMain">
            |<div class="symbol monospace"><span class="token keyword">interface </span><a href="index.html">Greeter</a></div>
            |<p class="paragraph">Greets people. Implemented by <code class="lang-kotlin">FormalGreeter</code>.</p>
            |<span class="kdoc-tag"><h4 class="">See also</h4><p class="paragraph">Other.</p></span>
            |</div></div></div>
            |<div class="tabbedcontent"><div class="tabs-section" tabs-section="tabs-section">
            |<button class="section-tab" data-active="">Members</button></div>
            |<div class="tabs-section-body"><div data-togglable="FUNCTION"><h2 class="tableheader">Functions</h2>
            |<div class="table"><a data-name="1%2FFunctions%2F2" anchor-label="welcome" id="1%2FFunctions%2F2"></a>
            |<div class="table-row table-row_content" data-filterable-current=":lib/commonMain" data-filterable-set=":lib/commonMain,:lib/androidMain">
            |<div class="main-subrow keyValue "><div class=""><span class="inline-flex"><div><a href="welcome.html"><span>welcome</span></a></div>
            |<span class="anchor-wrapper"><span class="anchor-icon"></span><div class="copy-popup-wrapper ">Link copied</div></span></span></div>
            |<div><div class="title"><div class="platform-hinted " data-platform-hinted="data-platform-hinted">
            |<div class="platform-bookmarks-row"><button class="platform-bookmark">common</button></div>
            |<div class="content sourceset-dependent-content" data-active="" data-togglable=":lib/commonMain">
            |<div class="symbol monospace"><span class="token keyword">abstract </span><span class="token keyword">fun </span><a href="welcome.html"><span class="token function">welcome</span></a><span class="token punctuation">(</span>key: String<span class="token punctuation">)</span></div>
            |<div class="brief "><p class="paragraph">Saves the value.</p></div></div></div></div></div></div></div></div>
            |</div></div></div></div>
            """.trimMargin()
        )
        page(
            "lib/com.example/-greeter/welcome.html",
            """
            |<div class="main-content" data-page-type="member" id="content">
            |<div class="breadcrumbs"><a href="../../index.html">lib</a><span class="delimiter">/</span>
            |<a href="../index.html">com.example</a><span class="delimiter">/</span><a href="index.html">Greeter</a>
