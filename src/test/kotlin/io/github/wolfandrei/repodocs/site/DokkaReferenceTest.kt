        )
        page("navigation.html", "<div class=\"sidebar\">nav</div>")
        page("other/index.html", "<div class=\"main-content\"><h1>Not a module</h1></div>")
    }

    private fun reference(language: String = "en") =
        DokkaReference(dir, listOf(ApiModuleEntry("lib", "lib")), UiText.of(language)).pages.associateBy { it.path }

    @Test
    fun `a type page has the kind, the name, the abstract, the platforms, the declaration, the overview and topics`() {
        val page = reference().getValue("api/lib/com.example/-greeter/index.html")
        val html = page.content

        assertEquals(ApiPageType.CLASSLIKE, page.type)
        assertEquals(SymbolKind.INTERFACE, page.kind)
        assertEquals("Greeter", page.title)
        assertTrue("<p class=\"symbol-kind\">Interface</p><h1>Greeter</h1>" in html) { html }
        assertTrue("<div class=\"symbol-abstract\"><p>Greets people.</p></div>" in html) { html }
        assertTrue("<li class=\"platform platform-common\">common</li>" in html) { html }
        assertTrue("<li class=\"platform platform-jvm\">android</li>" in html) { "platforms of the members: $html" }
        assertTrue("<h2 id=\"declaration\">Declaration</h2>" in html) { html }
        assertTrue("<span class=\"token keyword\">interface </span><a href=\"index.html\">Greeter</a>" in html)
        assertTrue("<h2 id=\"overview\">Overview</h2><p class=\"paragraph\">Implemented by" in html) { html }
        assertTrue("<h2>See also</h2>" in html) { html }
        assertTrue("<h2 id=\"topics\">Topics</h2><h3>Functions</h3>" in html) { html }
        assertTrue("<div class=\"topic\" id=\"1%2FFunctions%2F2\">" in html) { "anchors of the members stay: $html" }
        assertTrue("<a href=\"welcome.html\"><span class=\"token function\">welcome</span></a>" in html) { html }
        assertTrue("<div class=\"topic-abstract\"><p class=\"paragraph\">Saves the value.</p></div>" in html) { html }
        assertTrue("<nav class=\"breadcrumbs\" aria-label=\"Path\"><a href=\"../../index.html\">lib</a>" in html)
        listOf("Dokka header", "Dokka sidebar", "Generated by Dokka", "Link copied", "platform-bookmark", "<script")
            .forEach { chrome -> assertFalse(chrome in html) { "$chrome is dropped: $html" } }
    }

    @Test
    fun `a member page has the KDoc sections and its qualified title`() {
        val page = reference().getValue("api/lib/com.example/-greeter/welcome.html")

        assertEquals(SymbolKind.FUNCTION, page.kind)
        assertEquals("Greeter.welcome", page.qualifiedTitle)
        assertTrue("<h2>Parameters</h2><dl class=\"param-list\"><dt><code>key</code></dt>" in page.content) {
            page.content
        }
        assertEquals("Saves the value.", page.summary)
    }

    @Test
    fun `the labels follow the language`() {
        val html = reference("ru").getValue("api/lib/com.example/-greeter/index.html").content

        assertTrue("<p class=\"symbol-kind\">Интерфейс</p>" in html) { html }
        assertTrue("<h2 id=\"declaration\">Объявление</h2>" in html && "<h3>Функции</h3>" in html) { html }
    }

    @Test
    fun `the navigation of Dokka and the pages outside the modules are skipped`() {
        assertEquals(
            setOf("api/lib/com.example/-greeter/index.html", "api/lib/com.example/-greeter/welcome.html"),
            reference().keys,
        )
    }

    @Test
    fun `the search gets an entry per declaration`() {
        val entries = SearchIndex.apiEntries(reference().values, UiText.of("en"))

        assertEquals(
            listOf("Greeter (Interface, lib)", "Greeter.welcome (Function, lib)"),
            entries.map { it.title },
        )
        assertEquals("api/lib/com.example/-greeter/welcome.html", entries[1].url)
        assertTrue("Overwrites an old one." in entries[1].text) { entries[1].text }
    }
}
